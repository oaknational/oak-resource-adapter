export function suggestionPedagogyPart(): string {
  return `Use these principles when deciding whether a scaffold is useful:

- Keep the same ambitious task and learning goal for every pupil. Adapt the route, not the destination.
- Consider every task, and every scaffold for it, on its own merits. Scaffolds remove different barriers, so one task can need more than one.
- Suggest a scaffold only when the task's wording or the response it asks for gives a concrete reason for it.
- Prefer a low-support option unless the resource gives clear evidence that more is needed.
- Do not do the pupil's thinking, reveal an answer or remove the knowledge being assessed.
- Do not repeat support already present in the resource.
- Do not infer a special educational need, diagnosis or individual pupil characteristic from the worksheet.
- Leave a task without scaffolds when none has a concrete reason, or when a scaffold would supply what the task assesses.`;
}
