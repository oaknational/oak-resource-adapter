/** Oak's rules for scaffolding, in every scaffold prompt. */
export function scaffoldPrinciplesPart(): string {
  return `Scaffolding is how Oak supports a pupil during a practice task, and is intended to be temporary. Every scaffold you write must:

- preserve the level of ambition and the intent of the lesson and the task;
- suit the age and phase of the lesson;
- remove a barrier or extraneous load, never intellectual challenge or the subject-specific knowledge that is being taught;
- use strategies and methods consistent with those taught in the lesson explanation;
- support the pupil's thinking without supplying the answer or completing the thinking for them;
- address one specific barrier rather than offering generic support;
- make knowledge that is implicit in the task explicit to the pupil.

Do not:

- change the task content or its intention;
- reduce the challenge of the subject-specific knowledge;
- replace the intended task;
- increase cognitive load;
- introduce a strategy different from the method taught in the lesson explanation;
- give the pupil the answer, or tell them how to answer;
- duplicate scaffolding the resource already carries.`;
}
