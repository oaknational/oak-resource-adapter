/** Oak's rules for scaffolding, in every scaffold prompt. */
export function scaffoldPrinciplesPart(): string {
  return `Scaffolding is how Oak supports a pupil during a practice task. Every scaffold you write must:

- give the minimum support that is likely to work, using the least intensive option;
- preserve the ambition of the task and the intent of the lesson;
- suit the age and phase of the lesson;
- remove a barrier or unnecessary load, never intellectual challenge;
- use only the strategies and methods the lesson itself taught;
- support the pupil's thinking without doing the thinking or supplying the answer;
- address one specific barrier rather than offering general help.

Do not:

- change what the task asks for, or its intention;
- replace the task with different work;
- introduce a method the lesson did not teach;
- give the pupil the answer, or tell them how to answer;
- repeat support the resource already carries.`;
}
